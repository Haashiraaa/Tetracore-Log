# backend/src/api/schemas/common.py

"""Pieces shared by every schema module."""

from __future__ import annotations

import uuid
from datetime import datetime
from decimal import Decimal
from typing import Annotated, Any, Optional

from pydantic import BaseModel, BeforeValidator, ConfigDict, Field, field_validator

from backend.src.models import clean_full_name, clean_phone


def _not_a_flag(v: Any) -> Any:
    if isinstance(v, bool):  # JSON true/false would otherwise pass as 1/0
        raise ValueError("Must be a number, not true or false.")
    return v


# Gas bought (SCM). The app sends a decimal string such as "12.50" so no precision is lost;
# a JSON number is accepted too. true/false is not a number.
Gas = Annotated[Decimal, BeforeValidator(_not_a_flag)]


def require_tz(v: Optional[datetime]) -> Optional[datetime]:
    if v is not None and v.tzinfo is None:
        raise ValueError(
            "Timestamp must include a timezone offset, e.g. 2026-10-17T19:00:00+01:00")
    return v


class _SignInFields(BaseModel):
    """What every sign-in carries except the signature, which logs treat differently."""

    model_config = ConfigDict(str_strip_whitespace=True)

    id: uuid.UUID  # generated by the client; makes retries idempotent
    signed_in_at: Optional[datetime] = None  # default: server time
    device_id: Optional[str] = Field(default=None, max_length=64)

    @field_validator("signed_in_at")
    @classmethod
    def _tz_in(cls, v: Optional[datetime]) -> Optional[datetime]:
        return require_tz(v)

    @field_validator("device_id", check_fields=False)
    @classmethod
    def _blank_device(cls, v: Optional[str]) -> Optional[str]:
        return v or None


class EntrySignInRequest(_SignInFields):
    """What a log that always wants a fresh signature (trucks) needs to sign someone in."""

    signature: str = Field(min_length=1, max_length=400_000)  # PNG, base64. Required.


class _SignOutFields(BaseModel):
    """What every sign-out carries except the signature."""

    signed_out_at: Optional[datetime] = None  # default: server time

    @field_validator("signed_out_at")
    @classmethod
    def _tz_out(cls, v: Optional[datetime]) -> Optional[datetime]:
        return require_tz(v)


class EntrySignOutRequest(_SignOutFields):
    """What a log that always wants a fresh signature (trucks) needs to sign someone out.
    A log may add its own fields."""

    signature: str = Field(min_length=1, max_length=400_000)  # PNG, base64. Required.


class PersonSignInRequest(_SignInFields):
    """Visitors, staff and trucks: the signature may be left out when one is already on file
    for this person or plate (see entry_service.create_entry). Otherwise it is required."""

    signature: Optional[str] = Field(default=None, max_length=400_000)


class PersonSignOutRequest(_SignOutFields):
    """Visitors, staff and trucks: leave the signature out to reuse the one given at sign-in."""

    signature: Optional[str] = Field(default=None, max_length=400_000)


def full_name_field(v: str) -> str:
    """Validator body for every `full_name` / `driver_name`: see models.clean_full_name."""
    return clean_full_name(v)


def phone_field(v: str) -> str:
    """Validator body for a phone number that identifies a person: models.clean_phone."""
    return clean_phone(v)


def optional_phone_field(v: Optional[str]) -> Optional[str]:
    """Same, for a phone that may be left out: blank means "not given"."""
    return clean_phone(v) if v else None


class LookupOut(BaseModel):
    """What a gate officer sees when a returning person's phone is typed. The log adds
    its own fields. open_entry_id is set when they are inside right now."""

    full_name: str
    phone: str
    open_entry_id: Optional[uuid.UUID]
    # A signature from an earlier visit is on file, so they need not sign in again.
    has_signature: bool = False


def blank_to_none(v: Optional[str]) -> Optional[str]:
    """For optional text fields: an empty box means "not given"."""
    return v or None


class EntryOut(BaseModel):
    """What every log (trucks, visitors, staff) says about a sign-in. A log adds its own
    fields on top. Built from a row of db/queries/_entries.py:
    (entry, facility_code, has_signature_in, signed_in_by_name, signed_out_by_name,
    has_signature_out)."""

    id: uuid.UUID
    facility_id: uuid.UUID
    facility_code: str
    signed_in_at: datetime
    signed_out_at: Optional[datetime]
    signed_in_by: uuid.UUID
    signed_in_by_name: str
    signed_out_by: Optional[uuid.UUID]
    signed_out_by_name: Optional[str]
    device_id: Optional[str]
    gate_in: Optional[int]
    gate_out: Optional[int]
    has_signature: bool  # signed in
    has_signature_out: bool
    # Nobody drew it: copied from one on file (sign-in) or from sign-in (sign-out).
    signature_in_reused: bool
    signature_out_reused: bool
    created_at: datetime
    updated_at: datetime

    @staticmethod
    def common_fields(row: Any) -> dict[str, Any]:
        e, facility_code, has_sig_in, in_name, out_name, has_sig_out = row
        return dict(
            id=e.id, facility_id=e.facility_id, facility_code=facility_code,
            signed_in_at=e.signed_in_at, signed_out_at=e.signed_out_at,
            signed_in_by=e.signed_in_by, signed_in_by_name=in_name,
            signed_out_by=e.signed_out_by, signed_out_by_name=out_name,
            device_id=e.device_id, gate_in=e.gate_in, gate_out=e.gate_out,
            has_signature=bool(has_sig_in),
            has_signature_out=bool(has_sig_out),
            signature_in_reused=e.signature_in_reused,
            signature_out_reused=e.signature_out_reused,
            created_at=e.created_at, updated_at=e.updated_at,
        )
