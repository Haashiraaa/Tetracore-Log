# backend/src/api/schemas/occurrences.py

"""Events log: an officer's own note. The time, the officer and the gate are set by the
server; the officer only writes the note (and signs, if they have no signature on file)."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any, Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator

from backend.src.api.schemas.common import require_tz

MAX_NOTE = 2000


class OccurrenceCreateRequest(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True)

    id: uuid.UUID  # generated by the app; makes retries idempotent
    note: str = Field(min_length=3, max_length=MAX_NOTE)
    logged_at: Optional[datetime] = None  # default: server time
    # Only needed when the officer has no signature on file (they never signed on duty).
    signature: Optional[str] = Field(default=None, max_length=400_000)
    device_id: Optional[str] = Field(default=None, max_length=64)

    @field_validator("logged_at")
    @classmethod
    def _tz(cls, v: Optional[datetime]) -> Optional[datetime]:
        return require_tz(v)

    @field_validator("device_id")
    @classmethod
    def _blank_device(cls, v: Optional[str]) -> Optional[str]:
        return v or None


class OccurrenceOut(BaseModel):
    id: uuid.UUID
    facility_id: uuid.UUID
    facility_code: str
    officer_id: uuid.UUID
    officer_name: str
    gate: Optional[int]
    note: str
    logged_at: datetime
    has_signature: bool
    signature_reused: bool  # nobody drew it for this note: the officer's duty signature
    device_id: Optional[str]
    created_at: datetime
    updated_at: datetime

    @classmethod
    def from_row(cls, row: Any) -> "OccurrenceOut":
        e, facility_code, officer_name, has_signature = row
        return cls(
            id=e.id, facility_id=e.facility_id, facility_code=facility_code,
            officer_id=e.officer_id, officer_name=officer_name, gate=e.gate, note=e.note,
            logged_at=e.logged_at, has_signature=bool(has_signature),
            signature_reused=e.signature_reused, device_id=e.device_id,
            created_at=e.created_at, updated_at=e.updated_at)


class SignatureOnFileOut(BaseModel):
    """Whether the officer's duty signature can be used for a note."""

    has_signature: bool
