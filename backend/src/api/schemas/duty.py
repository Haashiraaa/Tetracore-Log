# backend/src/api/schemas/duty.py

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any, Optional

from pydantic import BaseModel, Field, field_validator

from backend.src.api.schemas.common import require_tz
from backend.src.models import MAX_GATES


class _AtMixin(BaseModel):
    at: Optional[datetime] = None  # default: server time

    @field_validator("at")
    @classmethod
    def _tz(cls, v: Optional[datetime]) -> Optional[datetime]:
        return require_tz(v)


class DutyOnRequest(_AtMixin):
    """Go on duty at a gate. The signature is optional: the app lets the officer sign or not."""

    id: uuid.UUID  # generated by the phone; makes retries idempotent
    gate: int = Field(ge=1, le=MAX_GATES)
    signature: Optional[str] = Field(default=None, max_length=400_000)
    device_id: Optional[str] = Field(default=None, max_length=64)

    @field_validator("device_id")
    @classmethod
    def _blank_device(cls, v: Optional[str]) -> Optional[str]:
        return v or None


class DutyChangeGateRequest(_AtMixin):
    id: uuid.UUID  # the new stretch's id
    gate: int = Field(ge=1, le=MAX_GATES)


class DutyOffRequest(_AtMixin):
    signature: Optional[str] = Field(default=None, max_length=400_000)


class DutyEntryOut(BaseModel):
    """One stretch of duty at one gate. Built from a row of db/queries/duty.py:
    (entry, facility_code, officer_name, officer_code, has_signature_in, has_signature_out)."""

    id: uuid.UUID
    facility_id: uuid.UUID
    facility_code: str
    officer_id: uuid.UUID
    officer_name: str
    officer_code: str
    gate: int
    shift_id: uuid.UUID
    on_duty_at: datetime
    off_duty_at: Optional[datetime]
    started_how: str  # on | moved
    ended_how: Optional[str]  # off | moved | admin
    device_id: Optional[str]
    has_signature: bool
    has_signature_out: bool

    @classmethod
    def from_row(cls, row: Any) -> "DutyEntryOut":
        e, facility_code, name, code, sig_in, sig_out = row
        return cls(
            id=e.id, facility_id=e.facility_id, facility_code=facility_code,
            officer_id=e.officer_id, officer_name=name, officer_code=code, gate=e.gate,
            shift_id=e.shift_id, on_duty_at=e.on_duty_at, off_duty_at=e.off_duty_at,
            started_how=e.started_how, ended_how=e.ended_how, device_id=e.device_id,
            has_signature=bool(sig_in), has_signature_out=bool(sig_out))


class DutyStatusOut(BaseModel):
    """Where this officer stands: the gates of their facility and their open stretch (if any)."""

    facility_code: str
    gate_count: int
    current: Optional[DutyEntryOut]
